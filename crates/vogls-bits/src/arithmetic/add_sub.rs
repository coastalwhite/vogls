use crate::VectorSize;
use crate::arithmetic::{fv_contains_special, fv_set_no_special};
use crate::load::load_partial_u64;
use crate::store::store_partial_u64;

use super::fv_ltu32_arith_op;

pub fn tv_ltu64_addition(dst: &mut [u8], lhs: &[u8], rhs: &[u8], size: VectorSize) {
    assert!(size.get() <= 64);
    let l = load_partial_u64(&lhs, size);
    let r = load_partial_u64(&rhs, size);
    let out = l.wrapping_add(r);
    store_partial_u64(dst, out, size);
}
pub fn tv_ltu64_subtraction(dst: &mut [u8], lhs: &[u8], rhs: &[u8], size: VectorSize) {
    assert!(size.get() <= 64);
    let l = load_partial_u64(&lhs, size);
    let r = load_partial_u64(&rhs, size);
    let out = l.wrapping_sub(r);
    store_partial_u64(dst, out, size);
}
pub fn fv_ltu32_addition(dst: &mut [u8], lhs: &[u8], rhs: &[u8], size: VectorSize) {
    fv_ltu32_arith_op(dst, lhs, rhs, size, |l, r| Some(l.wrapping_add(r)));
}
pub fn fv_ltu32_subtraction(dst: &mut [u8], lhs: &[u8], rhs: &[u8], size: VectorSize) {
    fv_ltu32_arith_op(dst, lhs, rhs, size, |l, r| Some(l.wrapping_sub(r)));
}

pub fn tv_addition_subtraction(
    dst: &mut [u64],
    lhs: &[u64],
    rhs: &[u64],
    size: VectorSize,
    subtract: bool,
) {
    assert!(
        dst.len() > 0
            && dst.len() == lhs.len()
            && dst.len() == rhs.len()
            && size.get().div_ceil(64) as usize == dst.len()
    );

    if dst.len() == 1 {
        let (lhs, rhs) = (lhs[0], rhs[0]);
        if subtract {
            dst[0] = lhs.wrapping_sub(rhs);
        } else {
            dst[0] = lhs.wrapping_add(rhs);
        }
        dst[0] &= 1u64.unbounded_shl(size.get()).wrapping_sub(1);
        return;
    }

    let mut carry_in = subtract;
    let mask = if subtract { !0u64 } else { 0u64 };
    for i in 0..dst.len() {
        (dst[i], carry_in) = lhs[i].carrying_add(rhs[i] ^ mask, carry_in);
    }
    if size.get() % 64 != 0 {
        *dst.last_mut().unwrap() &= (1u64 << (size.get() % 64)).wrapping_sub(1);
    }
}
pub fn fv_addition_subtraction(
    dst: &mut [u64],
    lhs: &[u64],
    rhs: &[u64],
    size: VectorSize,
    subtract: bool,
) {
    assert!(
        dst.len() > 0
            && dst.len() == lhs.len()
            && dst.len() == rhs.len()
            && dst.len() == 2 * size.get().div_ceil(64) as usize
    );

    if fv_contains_special(lhs, size) || fv_contains_special(rhs, size) {
        dst.fill(0);
        return;
    }

    fv_set_no_special(dst, size);
    let nwords = dst.len() / 2;
    tv_addition_subtraction(
        &mut dst[nwords..],
        &lhs[nwords..],
        &rhs[nwords..],
        size,
        subtract,
    );
}
pub fn tv_addition(dst: &mut [u64], lhs: &[u64], rhs: &[u64], size: VectorSize) {
    tv_addition_subtraction(dst, lhs, rhs, size, false)
}
pub fn tv_subtraction(dst: &mut [u64], lhs: &[u64], rhs: &[u64], size: VectorSize) {
    tv_addition_subtraction(dst, lhs, rhs, size, true)
}
pub fn fv_addition(dst: &mut [u64], lhs: &[u64], rhs: &[u64], size: VectorSize) {
    fv_addition_subtraction(dst, lhs, rhs, size, false)
}
pub fn fv_subtraction(dst: &mut [u64], lhs: &[u64], rhs: &[u64], size: VectorSize) {
    fv_addition_subtraction(dst, lhs, rhs, size, true)
}

