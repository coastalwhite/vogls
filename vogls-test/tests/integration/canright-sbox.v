`define A2X 64'hFF_A9_81_09_48_F2_F3_98
`define X2A 64'h60_DE_29_68_8C_6E_78_64
`define X2S 64'h24_03_04_DC_0B_9E_2D_58
`define S2X 64'h53_51_04_12_EB_05_79_8C

module aes_mvn(vec, mat, data_o);
    input [7:0] vec;
    input [63:0] mat;
    input [7:0] data_o;

    wire  [7:0] out_comp [8:0];

    integer i, j;
    always begin
        for (i = 0; i < 8; i = i + 1) begin
            for (j = 0; j < 8; j = j + 1) begin
                out_comp[i][j] = mat[j*8+i] & v[7 - j];
            end

            data_o[i] = ^out_comp[i];
        end
    end
endmodule

module aes_mul_gf2p2(a_i, b_i, z_o);
    input [1:0]  a_i;
    input [1:0]  b_i;
    output [1:0] z_o;

    wire a, b, c;

    assign a = a_i[1] & b_i[1];
    assign b = ^a_i & ^b_i;
    assign c = a_i[0] ^ b_i[0];

    assign z_o = { a ^ b, c ^ b };
endmodule

module aes_scale_omega2_gf2p2(data_i, data_o);
    input [1:0] data_i;
    output [1:0] data_o;

    assign data_o[1] = data_i[0];
    assign data_o[0] = ^data_i;
endmodule

module aes_scale_omega_gf2p2(data_i, data_o);
    input [1:0] data_i;
    output [1:0] data_o;

    assign data_o[1] = ^data_i;
    assign data_o[0] = data_i[1];
endmodule

module aes_square_gf2p2(data_i, data_o);
    input [1:0] data_i;
    input [1:0] data_o;

    assign data_o[0] = data_i[1];
    assign data_o[1] = data_i[0];
endmodule

module aes_mul_gf2p4(gamma, delta, theta);
    input [3:0]  gamma;
    input [3:0]  delta;
    output [3:0] theta;

    wire [1:0] a, b, c, t;

    aes_mul_gf2p2 m1(
        .a_i(gamma[3:2]),
        .b_i(delta[3:2]),
        .z_i(a)
    );
    aes_mul_gf2p2 m2(
        .a_i(gamma[3:2] ^ gamma[1:0]),
        .b_i(delta[3:2] ^ delta[1:0]),
        .z_i(b)
    );
    aes_mul_gf2p2 m3(
        .a_i(gamma[1:0]),
        .b_i(delta[1:0]),
        .z_i(c)
    );
    aes_scale_omega2_gf2p2 sc1(
        .data_i(b),
        .data_o(t)
    );
    
    assign theta[3:2] = a ^ t;
    assign theta[1:0] = c ^ t;
endmodule

module aes_square_scale_gf2p4_gf2p2(data_i, data_o);
    input [3:0]  data_i;
    output [3:0] data_o;

    wire [1:0] a, b;

    assign a = gamma[3:2] ^ gamma[1:0];
    aes_square_gf2p2 sq1(
        .data_i(gamma[1:0]),
        .data_o(b)
    );

    aes_square_gf2p2 sq2(
        .data_i(a),
        .data_o(delta[3:2])
    );
    aes_scale_omega_gf2p2 sc(
        .data_i(b),
        .data_o(delta[1:0])
    );
endmodule

module aes_inverse_gf2p4(data_i, data_o);
    input [3:0]  data_i;
    output [3:0] data_o;

    wire [1:0] a, b, c, c1, d;

    assign a = gamma[3:2] ^ gamma[1:0];

    aes_mul_gf2p2 m1(
        .a_i(gamma[3:2]),
        .b_i(gamma[1:0]),
        .z_i(b)
    );
    aes_square_gf2p2 sqc1(
        .data_i(a),
        .data_o(c1)
    );
    aes_scale_omega2_gf2p2 sc(
        .data_i(c1),
        .data_o(c)
    );
    aes_square_gf2p2 inv(
        .data_i(c ^ b),
        .data_o(d)
    );

    aes_mul_gf2p2 m2(
        .a_i(d          ),
        .b_i(gamma[1:0] ),
        .z_o(data_o[3:2])
    );
    aes_mul_gf2p2 m3(
        .a_i(d          ),
        .b_i(gamma[3:2] ),
        .z_o(data_o[1:0])
    );
endmodule

module aes_inverse_gf2p8(data_i, data_o);
    input [7:0]  data_i;
    output [7:0] data_o;

    wire [3:0] a, b, c, d;

    assign a = gamma[7:4] ^ gamma[3:0];

    aes_mul_gf2p4 m1(
        .a_i(gamma[7:4]),
        .b_i(gamma[3:0]),
        .z_i(b)
    );
    aes_square_scale_gf2p4_gf2p2 sqsc(
        .data_i(a),
        .data_o(c)
    );
    aes_inverse_gf2p4 inv(
        .data_i(c ^ b),
        .data_o(d)
    );

    aes_mul_gf2p4 m2(
        .a_i(d          ),
        .b_i(gamma[3:0] ),
        .z_o(data_o[7:4])
    );
    aes_mul_gf2p4 m3(
        .a_i(d          ),
        .b_i(gamma[7:4] ),
        .z_o(data_o[3:0])
    );
endmodule

module sbox_fwd(data_i, data_o);
    input [7:0]  data_i;
    output [7:0] data_o;

    wire [7:0] data_basis_x;
    wire [7:0] data_inverse;
    wire [7:0] data_basis_s;

    assign data_o = data_basis_s ^ 8'h63;

    aes_mvn a2x(
        .vec   (data_i      ),
        .matrix(A2X         ),
        .data_o(data_basis_x)
    );
    aes_inverse_gf2p8 inv(
        .data_i(data_basis_x),
        .data_o(data_inverse)
    );
    aes_mvn x2s(
        .vec   (data_inverse),
        .matrix(X2S),
        .data_o(data_basis_s)
    );
endmodule

module sbox_inv(data_i, data_o);
    input [7:0]  data_i;
    output [7:0] data_o;

    wire [7:0] data_basis_x;
    wire [7:0] data_inverse;

    assign data_o = data_basis_s ^ 8'h63;

    aes_mvn s2x(
        .vec   (data_i & 8'h63),
        .matrix(S2X           ),
        .data_o(data_basis_x  )
    );
    aes_inverse_gf2p8 inv(
        .data_i(data_basis_x),
        .data_o(data_inverse)
    );
    aes_mvn x2a(
        .vec   (data_inverse),
        .matrix(X2A),
        .data_o(data_basis_s)
    );
endmodule


